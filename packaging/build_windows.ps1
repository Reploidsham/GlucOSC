# Build dist\GlucOSC-windows-x64.zip on Windows (also used by the release workflow).
#
# Needs: Python 3.12 (python.org installer or the Microsoft Store version) on PATH as `python`,
#        and packaging\requirements-build.txt (made by `python packaging/lock_deps.py`;
#        every download is checked against its hash).
# Usage (PowerShell 7, from the repository folder; Windows PowerShell 5.1 writes zips with backslashes):
#     pwsh -ExecutionPolicy Bypass -File packaging\build_windows.ps1
$ErrorActionPreference = 'Stop'
if ($PSVersionTable.PSVersion.Major -lt 7) { throw 'Please run this with PowerShell 7 (pwsh).' }

$Root = Split-Path -Parent $PSScriptRoot
$AppName = 'GlucOSC'
$Src = Join-Path $Root 'src\glucose_osc_bridge.py'
$Lock = Join-Path $Root 'packaging\requirements-build.txt'
$Icon = Join-Path $Root 'branding\logo.ico'
$Work = Join-Path $Root 'build\windows'
$OutDir = Join-Path $Root 'dist'
$Out = Join-Path $OutDir 'GlucOSC-windows-x64.zip'

# Stop on a failing native command too (PowerShell does not do that by itself).
function Invoke-Checked {
    param([string]$Exe, [string[]]$Arguments)
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { throw "$Exe failed with exit code $LASTEXITCODE" }
}

if (-not (Test-Path $Lock) -or -not ((Get-Content $Lock -TotalCount 1) -like '# Generated by packaging/lock_deps.py*')) {
    throw "Missing or hand-made $Lock. Run: python packaging/lock_deps.py (then review and commit the file)"
}

if (Test-Path $Work) { Remove-Item -Recurse -Force $Work }
New-Item -ItemType Directory -Force -Path $Work, $OutDir | Out-Null

Write-Host '==> Creating build environment (hash-locked packages only)'
Invoke-Checked 'python' @('-m', 'venv', (Join-Path $Work 'venv'))
$Py = Join-Path $Work 'venv\Scripts\python.exe'
Invoke-Checked $Py @('-m', 'pip', 'install', '--disable-pip-version-check', '--no-cache-dir',
    '--require-hashes', '--only-binary=:all:', '--no-deps', '-r', $Lock)

Write-Host '==> Bundling with PyInstaller'
Invoke-Checked $Py @('-m', 'PyInstaller', '--noconfirm', '--clean', '--onedir', '--windowed',
    '--noupx', '--name', $AppName, '--icon', $Icon,
    '--distpath', (Join-Path $Work 'dist'), '--workpath', (Join-Path $Work 'pyi'), '--specpath', $Work,
    '--exclude-module', 'PySide6.QtWebEngineCore', '--exclude-module', 'PySide6.QtQml',
    $Src)

$Exe = Join-Path $Work "dist\$AppName\$AppName.exe"
if (-not (Test-Path $Exe)) { throw "Expected $Exe was not built" }

Write-Host '==> Adding license files of everything bundled'
Invoke-Checked $Py @((Join-Path $Root 'packaging\collect_licenses.py'), (Join-Path $Work "dist\$AppName\licenses"))

Write-Host '==> Zipping'
if (Test-Path $Out) { Remove-Item -Force $Out }
Compress-Archive -LiteralPath (Join-Path $Work "dist\$AppName") -DestinationPath $Out
Write-Host "Done: $Out"
