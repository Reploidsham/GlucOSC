#!/usr/bin/env python3
"""Write packaging/requirements-build.txt: exact versions + SHA-256 hashes of every build dependency.

Why: the release builds install PySide6 and PyInstaller from PyPI. Pinning every package (including
the ones they pull in) to an exact version *and* a hash means a build can only ever use files you
have already locked here. A newly published (possibly hijacked) release is never picked up by
accident, and a file swapped on the server would fail the hash check.

The "cooldown" skips any release younger than N days (default 14). Most malicious releases are
spotted and pulled within days, so waiting two weeks avoids the bulk of them.

Run on your own computer (needs Python 3.9+ with pip 22.2+ and internet access to pypi.org):

    python3 packaging/lock_deps.py              # newest versions that are >= 14 days old
    python3 packaging/lock_deps.py --cooldown 30

Then read the diff (`git diff packaging/requirements-build.txt`) and commit it. The CI builds refuse to
run without this file. Re-run it when you want to update the tools, not on every release.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import subprocess
import sys
import tempfile
import urllib.request
from typing import Callable, Dict, List, Optional, Set, Tuple

HERE = os.path.dirname(os.path.abspath(__file__))
IN_FILE = os.path.join(HERE, "requirements-build.in")
OUT_FILE = os.path.join(HERE, "requirements-build.txt")
HEADER_MARK = "# Generated by packaging/lock_deps.py"

PYTHON_VERSION = "3.12"         # must match the minor version in .github/workflows/release.yml
PYTHON_FULL_VERSION = "3.12.15"  # must match python-version in .github/workflows/release.yml
# Linux build runs on Ubuntu 22.04 (glibc 2.35). List every manylinux tag up to that.
LINUX_PLATFORMS = ([f"manylinux_2_{m}_x86_64" for m in range(35, 16, -1)]
                   + ["manylinux2014_x86_64", "manylinux2010_x86_64", "manylinux1_x86_64"])
TARGETS: Dict[str, List[str]] = {
    "linux": LINUX_PLATFORMS,
    "win32": ["win_amd64"],
}
TARGET_NAMES = {"linux": "Linux x86_64 (glibc 2.35+)", "win32": "Windows x64"}
# pip evaluates dependency markers (like `; sys_platform == "win32"`) against the machine it runs on,
# even with --platform. So this script walks the dependency tree itself with these environments.
_COMMON_ENV = {"python_version": PYTHON_VERSION, "python_full_version": PYTHON_FULL_VERSION,
               "implementation_name": "cpython", "implementation_version": PYTHON_FULL_VERSION,
               "platform_python_implementation": "CPython", "platform_release": "", "platform_version": "",
               "extra": ""}
TARGET_ENV = {
    "linux": dict(_COMMON_ENV, os_name="posix", sys_platform="linux", platform_system="Linux", platform_machine="x86_64"),
    "win32": dict(_COMMON_ENV, os_name="nt", sys_platform="win32", platform_system="Windows", platform_machine="AMD64"),
}
PYPI = "https://pypi.org/pypi"
PIP_INDEX_ARGS = ["--index-url", "https://pypi.org/simple"]

JsonFetcher = Callable[[str], dict]
PipRunner = Callable[[str, List[str], List[str]], List[dict]]


# ------------------------------------------------------------------ small helpers
def normalize(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def parse_time(text: str) -> dt.datetime:
    return dt.datetime.fromisoformat(text.replace("Z", "+00:00"))


def _version_key(v: str):
    try:
        from pip._vendor.packaging.version import Version  # pip is required anyway
        return (0, Version(v))
    except Exception:  # pragma: no cover - only if pip's vendored copy moves
        return (1, tuple(int(p) if p.isdigit() else p for p in v.replace("-", ".").split(".")))


def _is_prerelease(v: str) -> bool:
    try:
        from pip._vendor.packaging.version import Version
        return Version(v).is_prerelease
    except Exception:  # pragma: no cover
        return any(t in v for t in ("a", "b", "rc", "dev"))


def read_in_file(path: str = IN_FILE) -> List[Tuple[str, Optional[str]]]:
    """Top-level requirements: 'name' or 'name==version' per line."""
    out = []
    with open(path, encoding="utf-8") as fh:
        for line in fh:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            if "==" in line:
                name, ver = (p.strip() for p in line.split("==", 1))
                out.append((name, ver))
            elif any(c in line for c in "<>=!~;@ "):
                raise SystemExit(f"Only 'name' or 'name==version' lines are supported: {line!r}")
            else:
                out.append((line, None))
    return out


# ------------------------------------------------------------------ PyPI queries
def fetch_json(url: str) -> dict:
    req = urllib.request.Request(url, headers={"Accept": "application/json", "User-Agent": "GlucOSC-lock-deps"})
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.load(resp)


def first_upload(files: List[dict]) -> Optional[dt.datetime]:
    times = [parse_time(f["upload_time_iso_8601"]) for f in files if f.get("upload_time_iso_8601")]
    return min(times) if times else None


def newest_old_enough(project_json: dict, now: dt.datetime, cooldown_days: int) -> str:
    """Newest final, non-yanked release whose first file is at least cooldown_days old."""
    limit = now - dt.timedelta(days=cooldown_days)
    best = None
    for ver, files in project_json.get("releases", {}).items():
        if not files or _is_prerelease(ver) or all(f.get("yanked") for f in files):
            continue
        t = first_upload(files)
        if t is None or t > limit:
            continue
        if best is None or _version_key(ver) > _version_key(best):
            best = ver
    if best is None:
        raise SystemExit(f"No release of {project_json.get('info', {}).get('name')} is older than {cooldown_days} days")
    return best


def release_info(fetch: JsonFetcher, name: str, version: str) -> Tuple[Dict[str, Tuple[str, Optional[dt.datetime]]], bool]:
    """({filename: (sha256, upload time)}, yanked) for one release.

    The age check uses the exact file pip picked, not the release as a whole: a new, more specific
    wheel can be added to an old release later, and that new file is what would be installed."""
    data = fetch(f"{PYPI}/{name}/{version}/json")
    files = {}
    for f in data.get("urls", []):
        sha = f.get("digests", {}).get("sha256")
        when = parse_time(f["upload_time_iso_8601"]) if f.get("upload_time_iso_8601") else None
        if sha:
            files[f["filename"]] = (sha, when)
    return files, bool(data.get("info", {}).get("yanked"))


# ------------------------------------------------------------------ pip resolution
def run_pip(target: str, requirements: List[str], constraints: List[str]) -> List[dict]:
    """Resolve for one target platform with `pip install --dry-run --report` (nothing is installed)."""
    with tempfile.TemporaryDirectory() as tmp:
        req = os.path.join(tmp, "req.txt")
        con = os.path.join(tmp, "con.txt")
        rep = os.path.join(tmp, "report.json")
        with open(req, "w", encoding="utf-8") as fh:
            fh.write("\n".join(requirements) + "\n")
        with open(con, "w", encoding="utf-8") as fh:
            fh.write("\n".join(constraints) + "\n")
        cmd = [sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
               "--disable-pip-version-check", "--no-cache-dir", "--only-binary=:all:",
               "--python-version", PYTHON_VERSION, "--implementation", "cp",
               *PIP_INDEX_ARGS,
               "--report", rep, "-r", req, "-c", con]
        for plat in TARGETS[target]:
            cmd += ["--platform", plat]
        try:
            subprocess.run(cmd, check=True)
        except subprocess.CalledProcessError:
            raise SystemExit(
                f"pip could not find wheels for {target} ({', '.join(requirements)}).\n"
                "Usually the newest release dropped a platform. Pin an older version with == in "
                "packaging/requirements-build.in and run this script again.")
        with open(rep, encoding="utf-8") as fh:
            return json.load(fh).get("install", [])


def target_closure(items: List[dict], top_names: List[str], target: str):
    """Walk the resolved packages from the top-level names using the TARGET's markers.

    Returns (keys reachable on the target, requirement strings the target needs but pip left out).
    """
    from pip._vendor.packaging.requirements import Requirement
    env = TARGET_ENV[target]
    by_key = {normalize(it["metadata"]["name"]): it for it in items}
    reached: Set[str] = set()
    seen: Set[Tuple[str, frozenset]] = set()
    missing: List[str] = []
    missing_keys: Set[Tuple[str, frozenset]] = set()
    stack: List[Tuple[str, frozenset]] = []
    for n in top_names:
        r = Requirement(n)
        stack.append((normalize(r.name), frozenset(normalize(e) for e in r.extras)))
    while stack:
        key, extras = stack.pop()
        if (key, extras) in seen:
            continue
        seen.add((key, extras))
        it = by_key.get(key)
        if it is None:
            continue
        reached.add(key)
        for text in it["metadata"].get("requires_dist", []) or []:
            r = Requirement(text)
            if r.marker is not None:
                # A dependency counts if its marker holds with no extra or with any requested extra.
                if not any(r.marker.evaluate(dict(env, extra=e)) for e in ("",) + tuple(sorted(extras))):
                    continue
            dep = normalize(r.name)
            dep_extras = frozenset(normalize(e) for e in r.extras)
            if dep in by_key:
                stack.append((dep, dep_extras))
            elif (dep, dep_extras) not in missing_keys:
                missing_keys.add((dep, dep_extras))
                extra_txt = f"[{','.join(sorted(r.extras))}]" if r.extras else ""
                missing.append(f"{r.name}{extra_txt}{r.specifier}")
    return reached, missing


def parse_report(items: List[dict]) -> Dict[str, Tuple[str, str, str]]:
    """{normalized name: (display name, version, sha256)} from a pip report."""
    out = {}
    for it in items:
        meta = it["metadata"]
        info = it.get("download_info", {}).get("archive_info", {})
        sha = info.get("hashes", {}).get("sha256")
        if not sha and str(info.get("hash", "")).startswith("sha256="):
            sha = info["hash"].split("=", 1)[1]
        if not sha:
            raise SystemExit(f"pip gave no sha256 for {meta['name']} {meta['version']}")
        url = it.get("download_info", {}).get("url", "")
        out[normalize(meta["name"])] = (meta["name"], meta["version"], sha, url.rsplit("/", 1)[-1])
    return out


# ------------------------------------------------------------------ main logic
def resolve(top: List[Tuple[str, Optional[str]]], fetch: JsonFetcher, pip: PipRunner,
            now: dt.datetime, cooldown_days: int, max_rounds: int = 15):
    """Pick top-level versions, resolve every target, and push out releases younger than the cooldown."""
    reqs = []
    for name, ver in top:
        if ver is None:
            ver = newest_old_enough(fetch(f"{PYPI}/{name}/json"), now, cooldown_days)
        reqs.append(f"{name}=={ver}")
    pinned_top = {normalize(r.split("==")[0]) for r in reqs}
    limit = now - dt.timedelta(days=cooldown_days)
    excluded: Set[str] = set()
    checked: Dict[Tuple[str, str], Tuple[Dict[str, Tuple[str, Optional[dt.datetime]]], bool]] = {}
    warnings: List[str] = []

    top_names = [r.split("==")[0] for r in reqs]  # (extras, if any, stay in the name part)
    forced: Dict[str, List[str]] = {t: [] for t in TARGETS}  # deps pip skipped because of host markers
    for _round in range(max_rounds):
        results = {}
        for t in TARGETS:
            for _inner in range(max_rounds):
                items = pip(t, reqs + forced[t], sorted(excluded))
                keep, missing = target_closure(items, top_names, t)
                if not missing:
                    break
                forced[t] += [m for m in missing if m not in forced[t]]
            else:
                raise SystemExit(f"Could not complete the dependency tree for {t}")
            parsed = parse_report(items)
            results[t] = {k: v for k, v in parsed.items() if k in keep}
        too_young = []
        for t, res in results.items():
            for key, (name, ver, sha, filename) in res.items():
                if (key, ver) not in checked:
                    checked[(key, ver)] = release_info(fetch, name, ver)
                files, yanked = checked[(key, ver)]
                if not filename or filename not in files:
                    raise SystemExit(f"PyPI does not list {filename or '(no file name)'} for {name} {ver}; stopping to be safe")
                pypi_sha, uploaded = files[filename]
                if pypi_sha != sha:
                    raise SystemExit(f"Hash mismatch for {filename}: pip says {sha}, PyPI says {pypi_sha}")
                if uploaded is None:
                    raise SystemExit(f"PyPI gives no upload time for {filename}; stopping to be safe")
                if yanked:
                    raise SystemExit(f"{name} {ver} is yanked on PyPI; pin another version in requirements-build.in")
                if uploaded > limit:
                    if key in pinned_top:
                        warnings.append(f"{name}=={ver} is younger than {cooldown_days} days but is pinned in requirements-build.in")
                    else:
                        too_young.append(f"{name}!={ver}")
        if not too_young:
            return results, reqs, sorted(set(warnings))
        excluded.update(too_young)
    raise SystemExit("Could not find versions old enough after several rounds; try a smaller --cooldown")


def merge(results: Dict[str, Dict[str, Tuple[str, str, str, str]]]):
    """[(name, version, marker or None, [hashes])] covering every target."""
    by_pkg: Dict[Tuple[str, str], Dict[str, object]] = {}
    for target, res in results.items():
        for key, (name, ver, sha, _fn) in res.items():
            entry = by_pkg.setdefault((key, ver), {"name": name, "targets": set(), "hashes": set()})
            entry["targets"].add(target)
            entry["hashes"].add(sha)
    all_targets = set(results)
    rows = []
    for (key, ver), e in sorted(by_pkg.items()):
        targets = e["targets"]
        if targets == all_targets:
            marker = None
        else:
            marker = " or ".join(f'sys_platform == "{t}"' for t in sorted(targets))
        rows.append((e["name"], ver, marker, sorted(e["hashes"])))
    return rows


def render(rows, today: str, cooldown_days: int, warnings: List[str]) -> str:
    lines = [
        f"{HEADER_MARK} on {today} (UTC). Do not edit by hand; re-run the script.",
        f"# Python {PYTHON_VERSION}; targets: " + ", ".join(TARGET_NAMES[t] for t in TARGETS) + ".",
        f"# Cooldown: releases younger than {cooldown_days} days were skipped.",
        "# Install with: pip install --require-hashes --only-binary=:all: --no-deps -r packaging/requirements-build.txt",
    ]
    lines += [f"# WARNING: {w}" for w in warnings]
    for name, ver, marker, hashes in rows:
        head = f"{name}=={ver}" + (f" ; {marker}" if marker else "")
        lines.append(head + " \\")
        for i, h in enumerate(hashes):
            lines.append(f"    --hash=sha256:{h}" + (" \\" if i < len(hashes) - 1 else ""))
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description="Lock build dependencies with hashes.")
    p.add_argument("--cooldown", type=int, default=14, help="skip releases younger than this many days")
    p.add_argument("--output", default=OUT_FILE)
    a = p.parse_args(argv)
    now = dt.datetime.now(dt.timezone.utc)
    results, reqs, warnings = resolve(read_in_file(), fetch_json, run_pip, now, a.cooldown)
    text = render(merge(results), now.strftime("%Y-%m-%d"), a.cooldown, warnings)
    with open(a.output, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"Locked {', '.join(reqs)} and their dependencies -> {a.output}")
    for w in warnings:
        print("WARNING:", w)
    print("Review with `git diff`, then commit the file.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
