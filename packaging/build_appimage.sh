#!/usr/bin/env bash
# Build dist/GlucOSC-x86_64.AppImage on a Linux x86_64 machine (also used by the release workflow).
#
# Needs: python3 3.12 with venv, curl, and packaging/requirements-build.txt
#        (made by `python3 packaging/lock_deps.py`; every download is checked against its hash).
# Usage: bash packaging/build_appimage.sh
#
# Build on the oldest distro you care about: an AppImage bundles Qt and Python,
# but still uses the host's glibc, so one built on a newer system can fail on an older one.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
APP_NAME="GlucOSC"
SRC="$ROOT/src/glucose_osc_bridge.py"
LOCK="$ROOT/packaging/requirements-build.txt"
ICON="$ROOT/branding/logo_256.png"
WORK="$ROOT/build/linux"
OUT_DIR="$ROOT/dist"
OUT="$OUT_DIR/GlucOSC-x86_64.AppImage"

# Build tools downloaded from GitHub are fixed to one release each and checked against a hash
# (recorded 2026-11-05). To update one: change its version, download the file yourself, and put its
# `sha256sum` here. The build stops if a download does not match.
APPIMAGETOOL_VERSION="1.9.1"
APPIMAGETOOL_SHA256="ed4ce84f0d9caff66f50bcca6ff6f35aae54ce8135408b3fa33abfc3cb384eb0"
# The AppImage runtime (the small program at the start of every AppImage). appimagetool would
# otherwise download a moving "continuous" build, so it is pinned and passed in with --runtime-file.
RUNTIME_RELEASE="20251108"
RUNTIME_SHA256="2fca8b443c92510f1483a883f60061ad09b46b978b2631c807cd873a47ec260d"

[ "$(uname -m)" = "x86_64" ] || { echo "This script builds x86_64 only (you have $(uname -m))."; exit 1; }
[ -f "$SRC" ] || { echo "Missing $SRC"; exit 1; }

rm -rf "$WORK"
mkdir -p "$WORK" "$OUT_DIR"

if [ -n "${PREBUILT_DIST:-}" ]; then
  # Test hook: skip the Qt/PyInstaller step and wrap an existing folder.
  echo "==> Using prebuilt folder $PREBUILT_DIST"
  DIST="$PREBUILT_DIST"
else
  if ! head -n 1 "$LOCK" 2>/dev/null | grep -q '^# Generated by packaging/lock_deps.py'; then
    echo "Missing or hand-made $LOCK."
    echo "Run: python3 packaging/lock_deps.py   (then review and commit the file)"
    exit 1
  fi
  echo "==> Creating build environment (hash-locked packages only)"
  python3 -m venv "$WORK/venv"
  "$WORK/venv/bin/python" -m pip install --disable-pip-version-check --no-cache-dir \
    --require-hashes --only-binary=:all: --no-deps -r "$LOCK"

  echo "==> Bundling with PyInstaller"
  "$WORK/venv/bin/python" -m PyInstaller --noconfirm --clean --onedir --windowed --noupx \
    --name "$APP_NAME" \
    --distpath "$WORK/dist" --workpath "$WORK/pyi" --specpath "$WORK" \
    --exclude-module PySide6.QtWebEngineCore --exclude-module PySide6.QtQml \
    "$SRC"
  DIST="$WORK/dist/$APP_NAME"

  echo "==> Adding license files of everything bundled"
  "$WORK/venv/bin/python" "$ROOT/packaging/collect_licenses.py" "$DIST/licenses"
fi

[ -x "$DIST/$APP_NAME" ] || { echo "Expected executable $DIST/$APP_NAME not found."; exit 1; }

echo "==> Assembling AppDir"
APPDIR="$WORK/AppDir"
mkdir -p "$APPDIR/usr/lib/$APP_NAME" "$APPDIR/usr/share/icons/hicolor/256x256/apps"
cp -a "$DIST/." "$APPDIR/usr/lib/$APP_NAME/"

cat > "$APPDIR/AppRun" <<EOF
#!/bin/sh
HERE="\$(dirname "\$(readlink -f "\$0")")"
exec "\$HERE/usr/lib/$APP_NAME/$APP_NAME" "\$@"
EOF
chmod +x "$APPDIR/AppRun"

cat > "$APPDIR/glucosc.desktop" <<EOF
[Desktop Entry]
Type=Application
Name=GlucOSC
Comment=Blood Sugar Meter to OSC translation software
Exec=$APP_NAME
Icon=glucosc
Categories=Utility;
Terminal=false
EOF

cp "$ICON" "$APPDIR/glucosc.png"
cp "$ICON" "$APPDIR/usr/share/icons/hicolor/256x256/apps/glucosc.png"

echo "==> Fetching appimagetool $APPIMAGETOOL_VERSION"
TOOL="${APPIMAGETOOL:-$WORK/appimagetool-x86_64.AppImage}"
if [ -z "${APPIMAGETOOL:-}" ]; then
  curl -fsSL --retry 3 --proto '=https' --tlsv1.2 -o "$TOOL" \
    "https://github.com/AppImage/appimagetool/releases/download/$APPIMAGETOOL_VERSION/appimagetool-x86_64.AppImage"
fi
echo "$APPIMAGETOOL_SHA256  $TOOL" | sha256sum -c - || {
  echo "appimagetool does not match the recorded hash. Stopping: do not build with an unknown tool."
  exit 1
}
chmod +x "$TOOL"

echo "==> Fetching AppImage runtime $RUNTIME_RELEASE"
RUNTIME="${APPIMAGE_RUNTIME:-$WORK/runtime-x86_64}"
if [ -z "${APPIMAGE_RUNTIME:-}" ]; then
  curl -fsSL --retry 3 --proto '=https' --tlsv1.2 -o "$RUNTIME" \
    "https://github.com/AppImage/type2-runtime/releases/download/$RUNTIME_RELEASE/runtime-x86_64"
fi
echo "$RUNTIME_SHA256  $RUNTIME" | sha256sum -c - || {
  echo "AppImage runtime does not match the recorded hash. Stopping."
  exit 1
}

echo "==> Building AppImage"
# APPIMAGE_EXTRACT_AND_RUN lets the tool run where FUSE isn't available (CI, containers).
ARCH=x86_64 APPIMAGE_EXTRACT_AND_RUN=1 "$TOOL" --no-appstream --runtime-file "$RUNTIME" "$APPDIR" "$OUT"
chmod +x "$OUT"

echo
echo "Done: $OUT"
